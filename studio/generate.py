def _env():
    import jinja2

    env = jinja2.Environment(loader=jinja2.FileSystemLoader(str(P.TEMPLATES)), trim_blocks=True,
                             lstrip_blocks=True, keep_trailing_newline=True, undefined=jinja2.StrictUndefined,
                             autoescape=False)
    return env


def render(template: str, ctx: dict) -> str:
    text = _env().get_template(template).render(**ctx)
    while "\n\n\n" in text:                     # tidy blank runs left by skipped sections
        text = text.replace("\n\n\n", "\n\n")
    return text


def _backup_if_foreign(path: Path, backups: Path | None = None) -> Path | None:
    """Before overwriting CLAUDE.md / AGENTS.md: keep a copy if it isn't ours (someone wrote their own)."""
    if not path.exists():
        return None
    head = path.read_text(encoding="utf-8", errors="replace")[:600]
    if any(m in head for m in (GENERATED_MARK, BOOTSTRAP_MARK, *OLD_MARKS)):
        return None
    backups = backups or P.BACKUPS
    backups.mkdir(parents=True, exist_ok=True)
    dst = backups / f"{path.name}.{dt.datetime.now():%Y%m%d-%H%M%S}.bak"
    shutil.copy2(path, dst)
    return dst


